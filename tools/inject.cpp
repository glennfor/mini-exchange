/// \file inject.cpp
/// \brief Inject ITCH order flow into our engine and report the divergence.
///
/// Produces the table of spec 13.3. Read `docs/divergence.md` before reading
/// the numbers: ITCH is a market data feed, our engine is a matching engine,
/// and the differences between them are the point rather than a defect.

#include <algorithm>
#include <cstdio>
#include <cstdlib>
#include <string>
#include <vector>

#include "core/timestamp.hpp"

#include "book/fast_book.hpp"
#include "engine/event_sink.hpp"
#include "engine/matching_engine.hpp"
#include "feed/decoder.hpp"
#include "feed/mapped_file.hpp"
#include "replay/injector.hpp"

#include "tools/cli.hpp"

namespace {

using namespace miniex;

/// Feeds the engine's outbound events straight back to the injector's
/// accounting. `Fill` carries the resting order's id, which is the same
/// identity ITCH's `E`/`C` messages use.
struct InjectSink {
  Injector* injector{nullptr};
  std::uint64_t events{0};

  void emit(const Event& e) {
    ++events;
    if (e.type == EventType::Fill)
      injector->on_engine_fill(e.id, e.price, e.qty);
  }
};

using Engine = MatchingEngine<FastBook, InjectSink>;

struct Driver {
  Injector* injector{nullptr};
  Engine* engine{nullptr};
  std::size_t index{0};
  std::size_t applied{0};
  bool stopped{false};
  std::vector<Command> scratch;

  void operator()(const NormalizedEvent& e) {
    ++index;
    if (stopped) return;

    // The feed's own executions are the thing being compared against, never
    // injected.
    switch (e.action) {
    case MdAction::Execute:
    case MdAction::ExecuteWithPrice:
      if (injector->report().adds_injected > 0)
        injector->on_feed_execution(index, e);
      return;
    case MdAction::Trade: injector->on_feed_hidden(e.qty); return;
    case MdAction::Cross: injector->on_feed_cross(e.qty); return;
    default: break;
    }

    scratch.clear();
    const bool more = injector->translate(e, scratch, [this](OrderId ref) {
      RestingState out;
      const ConstOrderHandle h = engine->book().find(ref);
      if (h != nullptr) {
        out.price = h->price;
        out.qty = h->qty_open;
        out.found = true;
      }
      return out;
    });
    if (!more) {
      stopped = true;
      return;
    }
    for (const Command& c : scratch) {
      engine->apply(c);
      ++applied;
    }
  }
};

void print_table(const DivergenceReport& r) {
  const auto pct = [](std::uint64_t part, std::uint64_t whole) {
    return whole == 0
               ? 0.0
               : 100.0 * static_cast<double>(part) / static_cast<double>(whole);
  };

  std::printf("\n| Metric | Value |\n|---|---|\n");
  std::printf("| Add messages injected | %llu |\n",
              (unsigned long long)r.adds_injected);
  std::printf(
      "| Cancels / deletes / replaces injected | %llu / %llu / %llu |\n",
      (unsigned long long)r.cancels_injected,
      (unsigned long long)r.deletes_injected,
      (unsigned long long)r.replaces_injected);
  std::printf("| Adds our engine rejected | %llu |\n",
              (unsigned long long)r.adds_rejected);
  std::printf("| Trades generated by engine | %llu (%llu shares) |\n",
              (unsigned long long)r.engine_trades,
              (unsigned long long)r.engine_shares);
  std::printf("| Executions in the feed | %llu (%llu shares) |\n",
              (unsigned long long)r.feed_executions,
              (unsigned long long)r.feed_exec_shares);
  std::printf("| Matched (same resting order, same price) | %llu shares, "
              "%.1f%% |\n",
              (unsigned long long)r.matched_shares,
              100.0 * r.matched_fraction());
  std::printf("| Reference never injected (outside the window) | %llu shares, "
              "%.1f%% |\n",
              (unsigned long long)r.unknown_reference_shares,
              pct(r.unknown_reference_shares, r.feed_exec_shares));
  std::printf("| Explained by hidden liquidity (`P`) | %llu shares over %llu "
              "prints |\n",
              (unsigned long long)r.feed_hidden_shares,
              (unsigned long long)r.feed_hidden_prints);
  std::printf("| Explained by cross/auction (`Q`) | %llu shares over %llu "
              "crosses |\n",
              (unsigned long long)r.feed_cross_shares,
              (unsigned long long)r.feed_crosses);
  std::printf("| **Unexplained** | %llu shares, **%.1f%%** |\n",
              (unsigned long long)r.unmatched_shares,
              100.0 * r.unexplained_fraction());
  std::printf("| Engine traded, feed did not | %llu shares |\n",
              (unsigned long long)r.engine_only_shares);
  std::printf("| Price disagreements (should be 0) | %llu |\n",
              (unsigned long long)r.price_disagreements);

  std::printf("\nOf all trade volume in the feed, %.1f%% is structurally "
              "impossible\nfor this engine to produce (hidden prints and "
              "auction crosses).\n",
              100.0 * r.structurally_impossible_fraction());
}

} // namespace

int main(int argc, char** argv) {
  Cli cli("inject",
          "inject ITCH order flow into the matching engine and report the "
          "divergence from what the exchange actually did");
  cli.option("file", "the ITCH file to read", "", true);
  cli.option("locate", "stock locate to inject (0 = all; rarely useful)", "1");
  cli.option("max", "stop after this many injected commands (0 = all)", "0");
  cli.option("cases", "divergent cases to print", "10");
  cli.option("max-orders", "engine pool capacity", "1048576");
  if (!cli.parse(argc, argv)) return 2;

  const CycleCalibration cal(100);
  Cli::print_provenance(&cal);

  MappedFile file;
  if (!file.open(cli.get("file"))) {
    std::fprintf(stderr, "inject: %s\n", file.error().c_str());
    return 2;
  }

  Injector::Config icfg;
  icfg.symbol = static_cast<SymbolId>(cli.get_int("locate", 1));
  icfg.max_commands = static_cast<std::size_t>(cli.get_int("max", 0));
  icfg.keep_cases = static_cast<std::size_t>(cli.get_int("cases", 10)) * 2;
  Injector injector(icfg);

  FastBookConfig ladder;
  ladder.max_orders =
      static_cast<std::size_t>(cli.get_int("max-orders", 1048576));
  InjectSink sink;
  sink.injector = &injector;
  Engine engine(sink, EngineConfig{}, ladder);

  Driver driver;
  driver.injector = &injector;
  driver.engine = &engine;

  ItchDecoder decoder(file.data(), file.size(), driver);
  const Cycles t0 = now_cycles();
  const std::size_t decoded = decoder.decode(~std::size_t{0}, /*strict=*/false);
  const std::int64_t elapsed_ns = cal.cycles_to_ns(now_cycles() - t0);
  injector.finish();

  if (!decoder.failure().ok()) {
    std::fprintf(stderr, "inject: decode stopped: %s\n",
                 decoder.failure().what().c_str());
    return 1;
  }

  std::printf("\nstock locate %u, %zu messages decoded, %zu engine commands "
              "applied\n",
              icfg.symbol, decoded, driver.applied);
  if (elapsed_ns > 0) {
    std::printf("decode + inject + match: %.2f s (%.2f million messages/s)\n",
                (double)elapsed_ns / 1e9,
                (double)decoded / ((double)elapsed_ns / 1e9) / 1e6);
  }

  print_table(injector.report());

  const auto want_cases = static_cast<std::size_t>(cli.get_int("cases", 10));
  if (!injector.cases().empty() && want_cases > 0) {
    std::printf("\nindividual divergences (first %zu)\n",
                std::min(want_cases, injector.cases().size()));
    for (std::size_t i = 0; i < injector.cases().size() && i < want_cases;
         ++i) {
      const DivergenceCase& c = injector.cases()[i];
      std::printf("  message #%zu  ts=%lld  ref=%llu  feed %u @ %lld  -- %s\n",
                  c.message_index, (long long)c.ts, (unsigned long long)c.ref,
                  c.feed_qty, (long long)c.feed_price, c.reason);
    }
  }

  std::printf("\nRead docs/divergence.md before quoting any of this. ITCH is "
              "a market\ndata feed, not an order entry stream; these "
              "differences are the finding.\n");
  return 0;
}
